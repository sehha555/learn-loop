import Foundation

/// 講法只有兩種：給提示讓他自己算，或直接給完整做法（思路→分步算式→驗算→答案）。兩種都分區塊。
/// 之前四種（白話／引導／精簡／講義）混了「多詳細」「給不給答案」「版式」三個軸，選不乾淨，8/21 砍掉
enum TeachingStyle: String, CaseIterable {
	case hint, direct

	/// 舊存檔的值對回來：引導→提示，其他都是直接給
	static func from(stored raw: String?) -> TeachingStyle {
		switch raw {
		case "hint", "guided": .hint
		default: .direct
		}
	}

	var label: String {
		switch self {
		case .hint: "給提示"
		case .direct: "直接給做法"
		}
	}

	/// body 的形狀，兩種一樣：分區塊，區塊之間空一行；每塊可以有粗體標題、獨立式子、解說句
	var bodyRule: String {
		"""
		body 分成 2 到 6 個區塊，區塊之間空一行隔開（前面會自動編號，不要自己加編號或 ##）。
		每個區塊第一行是粗體標題（像「**第一步：求 $f_x$**」「**驗算**」「**答案**」，
		標題裡的符號也要用 $ 包，不要寫 f_x 這種原始碼），
		標題下一行就接內容、中間不要空行：要獨立成一行的式子單獨一行、前後用 $$ 包；解說用一般句子，
		直接對他說「你」。這裡允許 $$ 和 **粗體**，其他 markdown 不要用。不要前言不要總結。
		"""
	}

	/// 每一塊講到什麼程度
	var modeRule: String {
		switch self {
		case .hint:
			"""
			每一塊只給提示：這一步要做什麼、為什麼往這走、會用到哪個公式或觀察，
			不把算式算完、不給結果 —— 他要的是自己算出來。
			最後一塊標題「**卡住了就想**」，留一個有明確方向的小問題
			（「代哪兩個 x 值最快解出 A 和 B？」這種，不是「你覺得呢」）。不要有驗算、答案區塊。
			"""
		case .direct:
			"""
			先看他點的這個點是要算東西、還是在問觀念／為什麼／有什麼關聯。
			問觀念的：不要套下面的解題模板，第一塊就直接回答他問的那件事，
			後面最多再兩塊補為什麼，總共兩到三塊、不要「思路」「答案」這種標題。
			要算東西的：直接給完整做法，區塊照這個順序：
			- 「**思路**」：一兩句講整體方向（用什麼定理、為什麼）。
			- 每一步一塊（「**第一步：…**」「**第二步：…**」）：把這一步實際的算式用 $$ 獨立寫出來，
			  真的算到這一步的結果，不是只描述「做代換」「移項」；算式前後用一兩句講這行怎麼來、
			  關鍵技巧是什麼。
			- 「**驗算**」：代回去確認（能驗就驗，不能就省略這塊）。
			- 「**答案**」：一行寫最終結果。
			不要反問他。
			"""
		}
	}

	/// 直接問（沒有題目）時的開場句與點怎麼出
	var askStatusRule: String {
		switch self {
		case .hint:
			"""
			- status：一句話，直接對他說「你」—— 不給答案，講這個問題的切入點在哪，
			  結尾留一個有明確方向的小問題推他想。
			- points：2 到 4 個可以點開的點，依他該想的順序排列，每個是往下想的一步。
			"""
		case .direct:
			"""
			- status：一到兩句，直接對他說「你」—— 直接回答他問的事，給做法的骨幹
			  （例如「這是多項式乘三角函數，分部積分做兩次，第一次把 $u^2$ 當 f」）。
			  不要複述他的問題、不要只說「你在問的是…」。
			- points：2 到 4 個可以點開的點，依理解順序排列，是骨幹裡每一步的展開
			  （為什麼這樣選、下一步怎麼算、容易錯在哪），不是重講一次骨幹。
			"""
		}
	}
}
